// glyph metrics (trimmed proportional width)
const GLYPH = {};
for (const ch in FONT) {
  const rows = FONT[ch]; let minx = 5, maxx = -1;
  for (const r of rows) for (let x = 0; x < 5; x++) if (r[x] === '#') { if (x < minx) minx = x; if (x > maxx) maxx = x; }
  if (maxx < 0) { minx = 0; maxx = 2; }
  GLYPH[ch] = { rows, x0: minx, w: maxx - minx + 1 };
}
const glyphCache = {};
function glyphCanvas(ch, color) {
  const key = ch + color; if (glyphCache[key]) return glyphCache[key];
  const g = GLYPH[ch] || GLYPH['?'];
  const [c, gc] = mkCanvas(g.w, FONT_H); gc.fillStyle = color;
  for (let y = 0; y < g.rows.length; y++) for (let x = 0; x < 5; x++) if (g.rows[y][x] === '#') gc.fillRect(x - g.x0, y, 1, 1);
  glyphCache[key] = c; return c;
}
function normChar(ch) {
  if (ch === '’' || ch === '‘') return "'";
  if (ch === '“' || ch === '”') return '"';
  if (ch === '—' || ch === '–') return '-';
  if (ch === '…') return '.';
  return GLYPH[ch] ? ch : '?';
}
function textWidth(str) {
  let w = 0;
  for (let i = 0; i < str.length; i++) { const ch = normChar(str[i]); w += (ch === ' ' ? 3 : GLYPH[ch].w) + 1; }
  return Math.max(0, w - 1);
}
function drawText(g, str, x, y, color, opts) {
  opts = opts || {};
  if (opts.align === 'center') x -= Math.floor(textWidth(str) / 2);
  else if (opts.align === 'right') x -= textWidth(str);
  if (opts.shadow) { drawText(g, str, x + 1, y + 1, opts.shadow); }
  let cx = x;
  for (let i = 0; i < str.length; i++) {
    const ch = normChar(str[i]);
    if (ch === ' ') { cx += 4; continue; }
    g.drawImage(glyphCanvas(ch, color), cx, y); cx += GLYPH[ch].w + 1;
  }
  return cx - x;
}
function wrapText(str, maxW) {
  const words = str.split(' '); const lines = []; let cur = '';
  for (const w of words) {
    const t = cur ? cur + ' ' + w : w;
    if (textWidth(t) > maxW && cur) { lines.push(cur); cur = w; } else cur = t;
  }
  if (cur) lines.push(cur);
  return lines;
}

// ---------- sprites ----------
// A sprite is rows of chars; palette maps char -> css color. '.' = transparent.
const spriteCache = {};
function mkSprite(rows, pal, key) {
  if (key && spriteCache[key]) return spriteCache[key];
  const h = rows.length, w = Math.max(...rows.map(r => r.length));
  const [c, g] = mkCanvas(w, h);
  for (let y = 0; y < h; y++) for (let x = 0; x < rows[y].length; x++) {
    const ch = rows[y][x]; if (ch === '.' || ch === ' ') continue;
    const col = pal[ch]; if (!col) continue;
    g.fillStyle = col; g.fillRect(x, y, 1, 1);
  }
  if (key) spriteCache[key] = c;
  return c;
}
function flipH(c) {
  const [f, g] = mkCanvas(c.width, c.height);
  g.translate(c.width, 0); g.scale(-1, 1); g.drawImage(c, 0, 0); return f;
}
// silhouette (for shadows): same alpha, solid color
function silhouette(c, color) {
  const [s, g] = mkCanvas(c.width, c.height);
  g.drawImage(c, 0, 0); g.globalCompositeOperation = 'source-in'; g.fillStyle = color; g.fillRect(0, 0, c.width, c.height);
  return s;
}
// tint overlay
function tinted(c, color, alpha) {
  const [s, g] = mkCanvas(c.width, c.height);
  g.drawImage(c, 0, 0); g.globalCompositeOperation = 'source-atop'; g.globalAlpha = alpha; g.fillStyle = color; g.fillRect(0, 0, c.width, c.height);
  return s;
}
